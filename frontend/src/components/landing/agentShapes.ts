import type { PixelFrame } from './PixelMorph'

/**
 * 「智能体在做什么」五张卡的像素点阵。
 *
 * 为什么形状写在文件里、而不是画在组件里
 * ------------------------------------
 * 每组形状就是几行字符，改形状不需要懂 React、也不需要会画图：
 * 想给清单加一项，就照抄三行字符；想给表格加一列，就把竖线往右挪一格。
 * 组件只负责让这些字符动起来（见 PixelMorph.tsx）。
 *
 * 字符约定（与像素底座 pixelKit.ts 的语义一一对应）
 * ------------------------------------------------
 *   `.` 空     `#` 主色 ink      `B` 品牌色 brand
 *   `G` 完成 done              `W` 进行中 warn
 *
 * 硬性约束：**每组 13 行、每行 22 个字符**（对应 PixelMorph 里的 GRID_H / GRID_W）。
 * 行短了会被截断、长了会被丢掉，形状就会整体错位 —— 改完顺手数一下行宽。
 *
 * 每张卡四帧，是四个"节拍"
 * ----------------------
 * 帧的顺序就是播放顺序，最后一帧会变形回第一帧，所以：
 *   第 1 帧 = 「什么都还没发生」（空表、空幻灯片、只有坐标轴）
 *   第 2~3 帧 = 「正在做」（表头填上、数据一行行落进去）
 *   第 4 帧 = 「做完了」（全部打勾、柱子长齐、来源标出来）
 *
 * 四帧而不是三帧，是为了在中段多留一拍"进展"：两帧的过渡太快，看不出过程。
 * 也别再往上加 —— 四帧 × (18 拍停留 + 9 拍变形) 已经是 9.7 秒一轮，
 * 再多观众就等不到循环了。
 *
 * 注意第 2 帧之后各帧的方块数是**递增**的（表格 88 → 112 → 121 → 131）：
 * 少的那些会被 PixelMorph 补成位于重心的"幽灵"，于是新增的数据块是
 * 从中心飘出来就位的，而不是凭空闪现在格子里。
 */

export interface AgentShapeCard {
  title: string
  description: string
  /** 依次播放的像素图；最后一张会变形回第一张 */
  frames: PixelFrame[]
}

